export function getSeedCases(
  category: string,
  search: string,
  district: string,
  page: number,
  pageSize: number
): { cases: CaseRecord[]; total: number } {
  let filtered = SEED_CASES.filter((c) => c.category === category);

  if (district && district !== 'All Districts') {
    filtered = filtered.filter((c) => c.district === district);
  }

  if (search.trim()) {
    const q = search.trim().toLowerCase();
    filtered = filtered.filter(
      (c) =>
        c.case_number.toLowerCase().includes(q) ||
        c.case_name.toLowerCase().includes(q)
    );
  }

  filtered.sort((a, b) => b.case_date.localeCompare(a.case_date));

  const total = filtered.length;
  const start = (page - 1) * pageSize;
  const cases = filtered.slice(start, start + pageSize);

  return { cases, total };
}
